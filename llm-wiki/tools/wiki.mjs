#!/usr/bin/env node
// LLM Wiki helper — deterministic bookkeeping for the knowledge base. No dependencies (Node >= 18).
//   node llm-wiki/tools/wiki.mjs status   raw sources not yet ingested, open questions, recent log
//   node llm-wiki/tools/wiki.mjs index    regenerate wiki/index.md from page frontmatter
//   node llm-wiki/tools/wiki.mjs lint     check links, citations, frontmatter, index and log (exit 1 on errors)
// Layout: <kb>/raw (sources), <kb>/wiki (pages), <kb>/tools (this file); code paths are relative to <kb>/..
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const KB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.dirname(KB);
const RAW = path.join(KB, 'raw');
const WIKI = path.join(KB, 'wiki');
const TYPES = { overview: 'Overview', entity: 'Entities', concept: 'Concepts', analysis: 'Analyses' };
const SPECIAL = ['index.md', 'log.md'];

const LINK = /\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\\?\|[^\]]*)?\]\]/g;              // [[page]] or [[page|text]]
const RAW_CITE = /\[([A-Za-z0-9][\w.-]*):(\d+)(?:-(\d+))?(?:\s+«([^»]+)»)?\]/g; // [ID:12-18 «quote»]
const CODE_CITE = /\[code:([^\]#\s]+)(?:#([^\]\s]+))?\]/g;                     // [code:path#Symbol]
const LOG_HEADER = /^## \[\d{4}-\d{2}-\d{2}\] [a-z-]+ \| \S/;
const INGEST_HEADER = /^## \[[^\]]*\] ingest \| (.*)$/;

const read = (file) => fs.readFileSync(file, 'utf8').replace(/^﻿/, '').replace(/\r\n/g, '\n');
const walk = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir, { withFileTypes: true }) : [])
  .filter((e) => !e.name.startsWith('.'))
  .flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));
const rel = (from, file) => path.relative(from, file).split(path.sep).join('/');
const list = (value) => (value === undefined || value === '' ? [] : [].concat(value));
const logLines = () => (fs.existsSync(path.join(WIKI, 'log.md')) ? read(path.join(WIKI, 'log.md')).split('\n') : []);

function frontmatter(text) {
  const match = text.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!match) return { data: null, body: text };
  const data = {};
  for (const line of match[1].split('\n')) {
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (!kv) continue;
    const value = kv[2].trim();
    const unquote = (s) => s.trim().replace(/^["']|["']$/g, '');
    data[kv[1]] = value.startsWith('[') && value.endsWith(']')
      ? value.slice(1, -1).split(',').map(unquote).filter(Boolean)
      : unquote(value);
  }
  return { data, body: text.slice(match[0].length) };
}

function rawSources() {
  return walk(RAW).map((file) => {
    const text = read(file);
    const { data } = frontmatter(text);
    const id = data?.id || path.basename(file).replace(/\.[^.]+$/, '');
    return { id, file, lines: text.split('\n'), date: data?.date || '' };
  }).sort((a, b) => (a.date + a.id).localeCompare(b.date + b.id));
}

function ingestedIds() {
  return new Set(logLines().flatMap((l) => l.match(INGEST_HEADER)?.[1].match(/[\w.-]+/g) || []));
}

function wikiPages() {
  return walk(WIKI).filter((f) => f.endsWith('.md') && !SPECIAL.includes(rel(WIKI, f))).map((file) => {
    const text = read(file);
    const { data, body } = frontmatter(text);
    const prose = body.replace(/```[\s\S]*?```/g, '').replace(/`[^`\n]*`/g, '');
    return { name: path.basename(file, '.md'), file, path: rel(WIKI, file), data: data || {}, hasFrontmatter: !!data, prose };
  });
}

const normalize = (s) => s.toLowerCase().replace(/ё/g, 'е').replace(/[*_`#>|«»"“”„]/g, ' ').replace(/[‐-―]/g, '-').replace(/\s+/g, ' ').trim();

function quoteFound(lines, from, to, quote) {
  const span = normalize(lines.slice(from - 1, to).map((l) => l.replace(/^\s*(?:[-*+]|\d+\.)\s+/, '')).join(' '));
  let at = 0;
  for (const part of quote.split(/…|\.\.\./).map(normalize).filter(Boolean)) {
    const i = span.indexOf(part, at);
    if (i < 0) return false;
    at = i + part.length;
  }
  return true;
}

function buildIndex(pages) {
  const line = (p) => `- [${p.data.title || p.name}](${p.path}) — ${p.data.summary || ''}`.trimEnd();
  const out = ['<!-- generated by llm-wiki/tools/wiki.mjs index — do not edit -->', '# Index', '',
    `${pages.length} pages. Read this first, then open the pages you need.`, ''];
  const live = pages.filter((p) => p.data.status !== 'superseded');
  for (const [type, heading] of Object.entries(TYPES)) {
    const group = live.filter((p) => p.data.type === type).sort((a, b) => String(a.data.title).localeCompare(String(b.data.title), 'ru'));
    if (group.length) out.push(`## ${heading}`, '', ...group.map(line), '');
  }
  const old = pages.filter((p) => p.data.status === 'superseded');
  if (old.length) out.push('## Superseded', '', ...old.map((p) => `${line(p)} → [[${p.data.superseded_by}]]`), '');
  return out.join('\n');
}

function lint() {
  const errors = [];
  const warnings = [];
  const pages = wikiPages();
  const rawById = new Map(rawSources().map((r) => [r.id, r]));
  const byName = new Map();
  const inbound = new Map(pages.map((p) => [p.name, 0]));

  for (const p of pages) {
    if (byName.has(p.name)) errors.push(`${p.path}: page name "${p.name}" is used twice (also ${byName.get(p.name).path})`);
    byName.set(p.name, p);
  }
  for (const p of pages) {
    const at = p.path;
    if (!p.hasFrontmatter) { errors.push(`${at}: no frontmatter`); continue; }
    for (const key of ['title', 'type', 'summary', 'updated']) if (!p.data[key]) errors.push(`${at}: frontmatter "${key}" is missing`);
    if (p.data.type && !TYPES[p.data.type]) errors.push(`${at}: type "${p.data.type}" is not one of ${Object.keys(TYPES).join(', ')}`);
    if (p.data.status === 'superseded' && !byName.has(p.data.superseded_by)) errors.push(`${at}: superseded page needs "superseded_by: <existing page>"`);
    const sources = list(p.data.sources);
    for (const id of sources) if (!rawById.has(id)) errors.push(`${at}: sources lists unknown raw id "${id}"`);

    for (const m of p.prose.matchAll(LINK)) {
      const target = m[1].trim();
      if (byName.has(target)) inbound.set(target, inbound.get(target) + 1);
      else errors.push(`${at}: broken link [[${target}]]`);
    }
    for (const [text, id, a, b, quote] of p.prose.matchAll(RAW_CITE)) {
      const raw = rawById.get(id);
      if (!raw) { if (/^[A-Z]+-\d+$/.test(id)) errors.push(`${at}: ${text.slice(0, 40)} — unknown raw id "${id}"`); continue; }
      const from = Number(a); const to = Number(b || a);
      if (from < 1 || to < from || to > raw.lines.length) errors.push(`${at}: [${id}:${a}${b ? '-' + b : ''}] is outside ${rel(KB, raw.file)} (${raw.lines.length} lines)`);
      else if (quote && !quoteFound(raw.lines, from, to, quote)) errors.push(`${at}: quote «${quote}» is not in ${id}:${from}-${to}`);
      if (!sources.includes(id)) errors.push(`${at}: cites ${id} but "sources" does not list it`);
    }
    for (const [, file, symbol] of p.prose.matchAll(CODE_CITE)) {
      const target = path.join(REPO, file);
      if (!fs.existsSync(target)) errors.push(`${at}: code file not found: ${file}`);
      else if (symbol && !read(target).includes(symbol.split('::').pop())) errors.push(`${at}: "${symbol}" not found in ${file}`);
    }
  }
  for (const p of pages) if (p.data.type !== 'overview' && inbound.get(p.name) === 0) warnings.push(`${p.path}: orphan — no page links to it`);
  const ingested = ingestedIds();
  for (const raw of rawById.values()) if (!ingested.has(raw.id)) warnings.push(`raw/${rel(RAW, raw.file)}: not ingested yet`);

  const indexFile = path.join(WIKI, 'index.md');
  if (!fs.existsSync(indexFile) || read(indexFile).trim() !== buildIndex(pages).trim()) errors.push('index.md is stale — run: node llm-wiki/tools/wiki.mjs index');
  if (!fs.existsSync(path.join(WIKI, 'log.md'))) errors.push('log.md is missing');
  logLines().forEach((l, i) => {
    if (l.startsWith('## ') && !LOG_HEADER.test(l)) errors.push(`log.md:${i + 1}: header must look like "## [YYYY-MM-DD] ingest | Title"`);
  });

  for (const w of warnings) console.log(`warning  ${w}`);
  for (const e of errors) console.log(`ERROR    ${e}`);
  console.log(`lint: ${errors.length} error(s), ${warnings.length} warning(s), ${pages.length} pages`);
  return errors.length ? 1 : 0;
}

function status() {
  const ingested = ingestedIds();
  console.log('Raw sources (in ingest order):');
  for (const raw of rawSources()) console.log(`  ${ingested.has(raw.id) ? 'ingested' : 'NEW     '}  ${raw.id.padEnd(10)} ${rel(KB, raw.file)}`);
  console.log('\nOpen questions and contradictions:');
  for (const p of wikiPages()) p.prose.split('\n').forEach((l) => {
    if (/^>\s*\[!(question|contradiction)\]/i.test(l)) console.log(`  ${p.path}: ${l.replace(/^>\s*/, '').slice(0, 140)}`);
  });
  console.log('\nRecent log:');
  for (const l of logLines().filter((x) => x.startsWith('## [')).slice(-5)) console.log(`  ${l.slice(3)}`);
  return 0;
}

const commands = {
  status,
  index: () => { fs.writeFileSync(path.join(WIKI, 'index.md'), buildIndex(wikiPages())); console.log('index.md written'); return 0; },
  lint,
};
const command = commands[process.argv[2]];
if (!command) { console.log('usage: node llm-wiki/tools/wiki.mjs status | index | lint'); process.exit(2); }
process.exit(command());
